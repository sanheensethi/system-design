// Names lessons use that this icon version spells differently.
const ALIASES: Record<string, string> = {
  TriangleAlert: 'TriangleExclamationPoint',
  AlertTriangle: 'TriangleExclamationPoint',
  CircleAlert: 'CircleExclamationPoint',
  ShieldAlert: 'ShieldX',
  CheckCircle: 'CircleCheck',
  PieChart: 'ChartPie',
  SquareParking: 'ParkingMeter',
  Trash2: 'Trash',
  FileJson: 'FileBraces'
};

/** Resolve an icon by name: exact, then alias, then case-insensitive first letter, then a generic box. */
export function iconFor(name: string): LucideIcon {
  const pascal = name.charAt(0).toUpperCase() + name.slice(1);
  return ICONS[name] ?? ICONS[ALIASES[name] ?? ALIASES[pascal] ?? pascal] ?? Boxes;
}
